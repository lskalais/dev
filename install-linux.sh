#!/usr/bin/env bash
set -euo pipefail

if [[ "${EUID}" -ne 0 ]]; then
    printf 'Lancez ce script avec sudo : sudo ./install-linux.sh\n' >&2
    exit 1
fi

if ! command -v apt-get >/dev/null 2>&1 || ! command -v systemctl >/dev/null 2>&1; then
    printf 'Ce script nécessite Debian/Ubuntu avec apt et systemd.\n' >&2
    exit 1
fi

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="/etc/confidentia"
CONFIG_FILE="${CONFIG_DIR}/confidentia.env"
PRIVATE_STORAGE="/var/lib/confidentia/private-storage"

apt-get update
DEBIAN_FRONTEND=noninteractive apt-get install -y \
    openjdk-17-jdk maven mariadb-server tomcat10 openssl

tomcat_version="$(dpkg-query -W -f='${Version}' tomcat10)"
if [[ "${tomcat_version}" != 10.1.* ]]; then
    printf 'Tomcat 10.1 est requis, version installée : %s\n' "${tomcat_version}" >&2
    exit 1
fi

systemctl enable --now mariadb

if [[ -f "${CONFIG_FILE}" ]]; then
    # The file is generated by this installer and restricted to root.
    DB_PASSWORD="$(sed -n 's/^DB_PASSWORD=//p' "${CONFIG_FILE}")"
    APP_ENCRYPTION_KEY="$(sed -n 's/^APP_ENCRYPTION_KEY=//p' "${CONFIG_FILE}")"
    if ! printf '%s' "${DB_PASSWORD}" | grep -Eq '^[0-9a-f]{64}$'; then
        printf 'Mot de passe DB_PASSWORD invalide dans %s\n' "${CONFIG_FILE}" >&2
        exit 1
    fi
    if ! printf '%s' "${APP_ENCRYPTION_KEY}" | grep -Eq '^[A-Za-z0-9+/]{43}=$'; then
        printf 'Configuration existante invalide : %s\n' "${CONFIG_FILE}" >&2
        exit 1
    fi
else
    install -d -o root -g root -m 0700 "${CONFIG_DIR}"
    DB_PASSWORD="$(openssl rand -hex 32)"
    APP_ENCRYPTION_KEY="$(openssl rand -base64 32)"
    cat >"${CONFIG_FILE}" <<EOF
DB_HOST=127.0.0.1
DB_PORT=3306
DB_NAME=confidentia
DB_USER=confidentia_app
DB_PASSWORD=${DB_PASSWORD}
DB_SCHEMA_MODE=update
APP_ENCRYPTION_KEY=${APP_ENCRYPTION_KEY}
PRIVATE_STORAGE_DIR=${PRIVATE_STORAGE}
EOF
    chown root:root "${CONFIG_FILE}"
    chmod 0600 "${CONFIG_FILE}"
fi

if [[ ! -f "${CONFIG_FILE}" ]]; then
    printf 'Impossible de créer le fichier de configuration : %s\n' "${CONFIG_FILE}" >&2
    exit 1
fi
chown root:root "${CONFIG_DIR}" "${CONFIG_FILE}"
chmod 0700 "${CONFIG_DIR}"
chmod 0600 "${CONFIG_FILE}"

mariadb <<SQL
CREATE DATABASE IF NOT EXISTS confidentia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'confidentia_app'@'localhost' IDENTIFIED BY '${DB_PASSWORD}';
CREATE USER IF NOT EXISTS 'confidentia_app'@'127.0.0.1' IDENTIFIED BY '${DB_PASSWORD}';
ALTER USER 'confidentia_app'@'localhost' IDENTIFIED BY '${DB_PASSWORD}';
ALTER USER 'confidentia_app'@'127.0.0.1' IDENTIFIED BY '${DB_PASSWORD}';
GRANT ALL PRIVILEGES ON confidentia.* TO 'confidentia_app'@'localhost';
GRANT ALL PRIVILEGES ON confidentia.* TO 'confidentia_app'@'127.0.0.1';
SQL

install -d -o tomcat -g tomcat -m 0750 "${PRIVATE_STORAGE}"
install -d -o root -g root -m 0755 /etc/systemd/system/tomcat10.service.d
cat >/etc/systemd/system/tomcat10.service.d/confidentia.conf <<EOF
[Service]
EnvironmentFile=${CONFIG_FILE}
EOF

cd "${PROJECT_DIR}"
mvn --batch-mode --no-transfer-progress clean package
WAR="${PROJECT_DIR}/target/confidentia.war"
if [[ ! -f "${WAR}" ]]; then
    printf 'Le WAR construit est introuvable : %s\n' "${WAR}" >&2
    exit 1
fi
install -o tomcat -g tomcat -m 0640 "${WAR}" /var/lib/tomcat10/webapps/confidentia.war

systemctl daemon-reload
systemctl enable tomcat10
systemctl restart tomcat10

printf '\nInstallation terminée. Application : http://localhost:8080/confidentia/\n'
printf 'Configuration protégée : %s\n' "${CONFIG_FILE}"
printf 'Stockage privé : %s\n' "${PRIVATE_STORAGE}"
printf 'Conservez la clé APP_ENCRYPTION_KEY et les données ensemble; ne supprimez pas la configuration.\n'
